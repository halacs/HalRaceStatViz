#!/usr/bin/env python3
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import numpy as np
import os
import argparse

# Usage: python generate_plots.py --input <input_json> --title <event_title> [--output <output_prefix>]

WATERMARK_TEXT = "Generated by HalRaceStatViz"

def add_watermark(fig):
    fig.text(0.99, 0.01, WATERMARK_TEXT, ha='right', va='bottom',
             fontsize=9, color='#777777', alpha=0.7, fontstyle='italic')

def load_data(file_path):
    df = pd.read_json(file_path)
    df['netto_td'] = pd.to_timedelta(df['netto'])
    df['net_time_minutes'] = df['netto_td'].dt.total_seconds() / 60.0
    df['gender'] = df['kategoria'].str[0].map({'M': 'Férfi', 'W': 'Nő'})

    # Extract age category limits
    df['age_cat_start'] = df['kategoria'].str[1:].astype(int)

    # Map age start to age range string
    def map_age_range(age):
        if age == 16: return "16-17"
        elif age == 18: return "18-19"
        elif age == 20: return "20-24"
        elif age == 80: return "80+"
        else: return f"{age}-{age+4}"

    df['age_range'] = df['age_cat_start'].apply(map_age_range)
    return df

def generate_charts(file_name, event_title, prefix):
    if not os.path.exists(file_name):
        print(f"File not found: {file_name}")
        return

    df = load_data(file_name)

    out_dir = os.path.dirname(prefix)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    # Common settings matching your reference images
    plt.rcParams['font.family'] = 'sans-serif'
    sns.set_theme(style="whitegrid", rc={"axes.facecolor": "#ffffff", "grid.color": "#e0e0e0"})

    # Determine unique age ranges in logical order
    age_ranges = ["16-17", "18-19", "20-24", "25-29", "30-34", "35-39", "40-44",
                  "45-49", "50-54", "55-59", "60-64", "65-69", "70-74", "75-79", "80+"]
    existing_ranges = [r for r in age_ranges if r in df['age_range'].unique()]

    palette = {'Férfi': '#4A88B7', 'Nő': '#E77C7C'}

    # 1. Boxplot (Célidők eloszlása és szórása korosztályonként)
    fig1 = plt.figure(figsize=(16, 9))
    ax1 = sns.boxplot(data=df, x='age_range', y='net_time_minutes', hue='gender',
                      order=existing_ranges, palette=palette, fliersize=3,
                      linewidth=1.2, width=0.7)

    plt.title(f"{event_title}\nCélidők eloszlása és szórása korosztályonként - boxplot",
              fontsize=20, fontweight='bold', pad=30, color='#111A2C')
    plt.xlabel("Korosztály (év)", fontsize=12)
    plt.ylabel("Nettó célidő (ó:pp)", fontsize=12)

    # Format y-axis ticks as hours:minutes
    def minutes_to_hm(x, pos):
        h = int(x // 60)
        m = int(x % 60)
        return f"{h}:{m:02d}"

    ax1.yaxis.set_major_formatter(plt.FuncFormatter(minutes_to_hm))
    handles, labels = ax1.get_legend_handles_labels()
    ax1.legend(handles=handles, labels=labels, title="", loc='upper left', ncol=2, frameon=True)
    sns.despine(left=True, bottom=False)
    plt.tight_layout()
    add_watermark(fig1)
    fig1.savefig(f"{prefix}_boxplot_celidok_kategoriankent.jpg", dpi=300)
    plt.close(fig1)

    # 2. Histogram (Célidők megoszlása)
    fig2 = plt.figure(figsize=(16, 9))
    ax2 = sns.histplot(data=df, x='net_time_minutes', hue='gender',
                       bins=20, kde=True, palette=palette,
                       alpha=0.6, element="bars")

    plt.title(f"{event_title}\nCélidők megoszlása",
              fontsize=20, fontweight='bold', pad=30, color='#111A2C')
    plt.ylabel("Futók száma", fontsize=12)
    ax2.xaxis.set_major_formatter(plt.FuncFormatter(minutes_to_hm))
    ax2.set_xlabel("Nettó célidő (ó:pp)", fontsize=12)

    avg_m = df[df['gender'] == 'Férfi']['net_time_minutes'].mean()
    avg_w = df[df['gender'] == 'Nő']['net_time_minutes'].mean()
    plt.axvline(x=avg_m, color='#3170A0', linestyle='--', linewidth=2)
    plt.axvline(x=avg_w, color='#D85E5E', linestyle='--', linewidth=2)

    from matplotlib.lines import Line2D
    from matplotlib.patches import Patch
    m_h, m_m, m_s = int(avg_m // 60), int(avg_m % 60), int((avg_m * 60) % 60)
    w_h, w_m, w_s = int(avg_w // 60), int(avg_w % 60), int((avg_w * 60) % 60)

    legend_elements = [
        Patch(facecolor=palette['Férfi'], alpha=0.6, label=f"Férfi - {len(df[df['gender'] == 'Férfi'])} fő"),
        Patch(facecolor=palette['Nő'], alpha=0.6, label=f"Nő - {len(df[df['gender'] == 'Nő'])} fő"),
        Line2D([0], [0], color='#3170A0', linestyle='--', lw=2, label=f'Férfi átlag - {m_h}:{m_m:02d}:{m_s:02d}'),
        Line2D([0], [0], color='#D85E5E', linestyle='--', lw=2, label=f'Nő átlag - {w_h}:{w_m:02d}:{w_s:02d}')
    ]
    ax2.legend(handles=legend_elements, loc='upper right', ncol=2, frameon=True)
    sns.despine(left=True)
    plt.tight_layout()
    add_watermark(fig2)
    fig2.savefig(f"{prefix}_celidok_megoszlasa.jpg", dpi=300)
    plt.close(fig2)

    # 3. Bar chart (Korosztályos kategóriák létszáma)
    fig3 = plt.figure(figsize=(16, 9))
    count_data = df.groupby(['age_range', 'gender']).size().reset_index(name='count')
    ax3 = sns.barplot(data=count_data, x='age_range', y='count', hue='gender',
                      order=existing_ranges, palette=palette)

    plt.title(f"{event_title}\nKorosztályos kategóriák létszáma - életkor szerint",
              fontsize=20, fontweight='bold', pad=30, color='#111A2C')
    plt.xlabel("Korosztály (év)", fontsize=12)
    plt.ylabel("Futók száma", fontsize=12)

    for p in ax3.patches:
        height = p.get_height()
        if pd.notnull(height) and height > 0:
            ax3.annotate(f'{int(height)}', (p.get_x() + p.get_width() / 2., height),
                         ha='center', va='bottom', xytext=(0, 3),
                         textcoords='offset points', fontsize=10, color=p.get_facecolor())

    ax3.legend(title="", loc='upper right', ncol=2, frameon=True)
    sns.despine(left=True)
    plt.tight_layout()
    add_watermark(fig3)
    fig3.savefig(f"{prefix}_korcsoport_letszam_eletkor_szerint.jpg", dpi=300)
    plt.close(fig3)

    # 4. Horizontal Bar chart (TOP 10 küldő ország)
    fig4 = plt.figure(figsize=(12, 10))
    top_countries = df['orszag'].value_counts().head(10)
    ax4 = sns.barplot(x=top_countries.values, y=top_countries.index, color='#267B88', width=0.6)

    plt.title(f"{event_title}\nTOP 10 küldő ország",
              fontsize=20, fontweight='bold', pad=40, color='#111A2C')
    plt.xlabel("Futók száma", fontsize=12)
    plt.ylabel("Országkód", fontsize=12)

    for i, p in enumerate(ax4.patches):
        ax4.text(p.get_width() + max(top_countries.values)*0.01,
                 p.get_y() + p.get_height()/2,
                 f'{int(p.get_width())}', ha='left', va='center', fontsize=11)

    sns.despine(left=True, bottom=False)
    plt.tight_layout()
    add_watermark(fig4)
    fig4.savefig(f"{prefix}_top10_orszag.jpg", dpi=300)
    plt.close(fig4)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate Marathon Charts")
    parser.add_argument("--input", required=True, help="Input JSON file path")
    parser.add_argument("--title", required=True, help="Event title string for the charts header (e.g. 'Budapest SPAR Maraton - 30 km - 2026. október 11.')")
    parser.add_argument("--output", "--prefix", dest="prefix", default=None, help="Output file prefix (e.g. 'output/30km')")
    parser.add_argument("--dist", default=None, help="Distance label (optional, used as fallback for prefix if output not specified)")
    args = parser.parse_args()

    event_title = args.title
    if args.prefix:
        prefix = args.prefix
    elif args.dist:
        prefix = args.dist.replace(" ", "").lower()
    else:
        base_name = os.path.splitext(os.path.basename(args.input))[0]
        prefix = os.path.join("output", base_name)

    print(f"Generating charts for {args.input}...")
    generate_charts(args.input, event_title, prefix)
    print("Done!")